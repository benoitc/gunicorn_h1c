"""pytest plugin: record every input the test suite feeds to gunicorn_h1c that
raises a parse error, with the keyword arguments used.

It regenerates tests/data/invalid_corpus.py, the inputs that
tests/test_error_split.py replays at every split point:

    H1C_CORPUS=tests/data/invalid_corpus.py PYTHONPATH=tests:src \
        pytest -p record_invalid_corpus tests/ --ignore=tests/test_error_split.py
"""

import os

import gunicorn_h1c as g

RECORDED = []
SEEN = set()
INCOMPLETE = (g.IncompleteError, g._parser_fast.IncompleteError)
ERRORS = (g.ParseError, g._parser_fast.ParseError, g._protocol.ParseError)
ONE_SHOT = (
    "parse_request",
    "parse_request_fast",
    "parse_to_wsgi_environ",
    "parse_to_asgi_scope",
)


def record(entry, data, kwargs):
    kw = {k: v for k, v in kwargs.items() if k.startswith(("limit_", "permit_"))}
    key = (entry, bytes(data), tuple(sorted(kw.items())))
    if key not in SEEN:
        SEEN.add(key)
        RECORDED.append((entry, bytes(data), kw))


def wrap(name, func):
    def wrapper(data, *args, **kwargs):
        try:
            return func(data, *args, **kwargs)
        except INCOMPLETE:
            raise
        except ERRORS:
            if kwargs.get("last_len", 0) == 0 and not args:
                record(name, data, kwargs)
            raise

    wrapper.__name__ = name
    return wrapper


class RecordingProtocol(g.H1CProtocol):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._rec_kwargs = kwargs
        self._rec_data = bytearray()

    def feed(self, data):
        self._rec_data += bytes(data)
        try:
            return super().feed(data)
        except ERRORS:
            if not any(callable(v) for v in self._rec_kwargs.values()):
                record("H1CProtocol", self._rec_data, self._rec_kwargs)
            raise

    def reset(self):
        self._rec_data = bytearray()
        return super().reset()


def pytest_configure(config):
    for name in ONE_SHOT:
        setattr(g, name, wrap(name, getattr(g, name)))
    g.H1CProtocol = RecordingProtocol


def pytest_unconfigure(config):
    path = os.environ.get("H1C_CORPUS", "invalid_corpus.py")
    with open(path, "w") as f:
        f.write('"""Generated by tests/record_invalid_corpus.py; do not edit."""\n\n')
        f.write("CASES = [\n")
        for entry, data, kw in RECORDED:
            f.write(f"    ({entry!r}, {data!r}, {kw!r}),\n")
        f.write("]\n")
